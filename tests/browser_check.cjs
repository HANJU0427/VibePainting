// Run against tests/serve_fixture.py; requires Playwright and a Chromium browser.
const {chromium} = require('playwright');
const assert = require('node:assert/strict');
const path = require('node:path');
const fs = require('node:fs');
(async () => {
  const browser = await chromium.launch({channel: 'msedge', headless: true});
  const page = await browser.newPage({viewport: {width: 1440, height: 1080}});
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('http://127.0.0.1:8767');
  await page.waitForLoadState('networkidle');
  await page.locator('#file-input').setInputFiles(path.join(__dirname, '../output_landscape.png'));
  await page.locator('#canvas-stack').waitFor({state: 'visible'});
  assert.equal(await page.locator('#generate').isDisabled(), true);
  const rect = await page.locator('#mask-canvas').boundingBox();
  const x = rect.x + rect.width / 2, y = rect.y + rect.height / 2;
  const centerAlpha = () => page.evaluate(() => {
    const canvas = document.getElementById('mask-canvas');
    return canvas.getContext('2d').getImageData(canvas.width / 2, canvas.height / 2, 1, 1).data[3];
  });
  await page.mouse.move(x - 35, y); await page.mouse.down(); await page.mouse.move(x + 35, y, {steps: 12}); await page.mouse.up();
  assert.equal(await centerAlpha(), 255);
  assert.equal(await page.locator('#generate').isEnabled(), true);
  await page.locator('#eraser').click(); await page.mouse.click(x, y);
  assert.equal(await centerAlpha(), 0);
  await page.locator('#undo').click(); await page.waitForFunction(() => !document.getElementById('undo').disabled);
  assert.equal(await centerAlpha(), 255);
  await page.locator('#clear').click(); assert.equal(await centerAlpha(), 0);
  assert.equal(await page.locator('#generate').isDisabled(), true);
  await page.locator('#undo').click(); await page.waitForFunction(() => !document.getElementById('generate').disabled);
  await page.locator('#show-mask').uncheck(); assert.match(await page.locator('#mask-canvas').getAttribute('class'), /mask-hidden/);
  await page.locator('#show-mask').check();
  const maskDownload = page.waitForEvent('download'); await page.locator('#save-mask').click();
  assert.equal((await maskDownload).suggestedFilename(), 'vibepainting-mask.png');
  await page.locator('#prompt').fill('a small flower garden in warm sunlight');
  await page.locator('#generate').click();
  await page.waitForFunction(() => document.getElementById('generate-label').textContent === '正在生成…');
  assert.equal(await page.locator('#file-input').isDisabled(), true);
  await page.locator('#result-image').waitFor({state: 'visible'});
  await page.waitForFunction(() => !document.getElementById('use-result').disabled);
  assert.match(await page.locator('#status').textContent(), /完成，用时/);
  const generated = await page.locator('#result-image').getAttribute('src');
  // Verify the accessible hold-to-compare path.
  await page.locator('#compare').focus(); await page.keyboard.down('Space');
  assert.notEqual(await page.locator('#result-image').getAttribute('src'), generated);
  await page.keyboard.up('Space'); assert.equal(await page.locator('#result-image').getAttribute('src'), generated);
  const download = page.waitForEvent('download'); await page.locator('#download').click();
  assert.match((await download).suggestedFilename(), /^vibepainting-.*\.png$/);
  fs.mkdirSync(path.join(__dirname, '../test_artifacts'), {recursive: true});
  await page.screenshot({path: path.join(__dirname, '../test_artifacts/workbench-desktop.png'), fullPage: true});
  await page.locator('#use-result').click(); await page.waitForFunction(() => !document.getElementById('brush').disabled);
  assert.equal(await centerAlpha(), 0);
  assert.equal(await page.locator('#generate').isDisabled(), true);
  await page.setViewportSize({width: 390, height: 844});
  await page.screenshot({path: path.join(__dirname, '../test_artifacts/workbench-mobile.png'), fullPage: true});
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  assert.deepEqual(errors, []);
  await browser.close();
  console.log('PASS: upload, brush, eraser, undo, clear, visibility, export, generation, compare, download, reuse, responsive layout.');
})().catch(error => { console.error(error); process.exit(1); });
